    if op == 'bool_array':
        return 'new bool[%d]' % f['count']
    if op == 'object_array':
        return 'global::Anki.Cozmo.Sdk.Clad.CladArrays.New<%s>(%d)' % (qualified(f['type']), f['count'])
    if op == 'object':
        return 'new %s()' % qualified(f['type'])
    if op in ('varray', 'bool_varray', 'string_varray', 'object_varray'):
        return 'System.Array.Empty<%s>()' % field_type(f).replace('[]', '')
    raise ValueError('unknown op %r' % op)


