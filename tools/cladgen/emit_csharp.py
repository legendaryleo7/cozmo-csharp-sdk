def short(fqn):
    return fqn.rsplit('.', 1)[1]


def ns(fqn):
    return fqn.rsplit('.', 1)[0]


def qualified(fqn):
    return 'global::' + fqn


def scalar_type(code):
    return SCALARS[code][0]


def read_method(code):
    return 'Read' + SCALARS[code][1]


def write_method(code):
    return 'Write' + SCALARS[code][1]


def string_suffix(code):
    return LEN[code][0]


def len_max(code):
    return LEN[code][1]


