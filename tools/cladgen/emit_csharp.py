    if op == 'bool_array':
        return 'bool[]'
    if op == 'varray':
        return scalar_type(f['code']) + '[]'
    if op == 'bool_varray':
        return 'bool[]'
    if op == 'string_varray':
        return 'string[]'
    if op == 'object':
        return qualified(f['type'])
    if op in ('object_array', 'object_varray'):
        return qualified(f['type']) + '[]'
    raise ValueError('unknown op %r' % op)


