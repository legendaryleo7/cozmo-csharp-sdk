    lines.append('    }')
    lines.append('')
    lines.append('    /// <summary>Reads an alternative from the wire.</summary>')
    lines.append('    public void Unpack(global::Anki.Cozmo.Sdk.Clad.CladBinaryReader cladReader)')
    lines.append('    {')
    lines.append('        _tag = (Tag)cladReader.%s();' % tag_read)
    lines.append('        switch (_tag)')
    lines.append('        {')
    for a in alts:
        lines.append(alt_unpack_line(a))
    lines.append('            default: throw new System.IO.InvalidDataException($"Unknown %s tag {_tag}.");' % name)
    lines.append('        }')
    lines.append('    }')
