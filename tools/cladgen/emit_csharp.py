    tag_read = read_method(t['tag_code'])
    lines.append('/// <summary>CLAD union <c>%s</c>.</summary>' % fqn)
    lines.append('public sealed partial class %s' % name)
    lines.append('{')
    lines.append('    /// <summary>Alternative selected by this union.</summary>')
    lines.append('    public enum Tag : %s' % tag_type)
    lines.append('    {')
    alts = t['alternatives']
    for i, a in enumerate(alts):
        comma = ',' if i < len(alts) - 1 else ''
        lines.append('        %s = %d%s' % (a['name'], a['value'], comma))
    lines.append('    }')
    lines.append('')
    lines.append('    private Tag _tag;')
    lines.append('    private object? _state;')
    lines.append('')
    lines.append('    /// <summary>Currently selected alternative.</summary>')
    lines.append('    public Tag tag => _tag;')
    lines.append('')
    lines.append('    /// <summary>True when an alternative has been set.</summary>')
    lines.append('    public bool HasValue => _state is not null;')
    lines.append('')
    lines.append('    /// <summary>Clears the selected alternative.</summary>')
    lines.append('    public void Clear()')
    lines.append('    {')
    lines.append('        _tag = default;')
    lines.append('        _state = null;')
    lines.append('    }')
    for a in alts:
        atype = alt_cs_type(a)
        payload = a['payload']
        lines.append('')
        lines.append('    /// <summary>Alternative <c>%s</c>.</summary>' % a['name'])
        lines.append('    public %s %s' % (atype, a['name']))
        lines.append('    {')
        if payload['op'] == 'object':
            lines.append('        get => _tag == Tag.%s && _state is %s value' % (a['name'], atype))
            lines.append('            ? value')
            lines.append('            : throw new System.InvalidOperationException($"Cannot access union member \\"%s\\" when %s stores {_tag}.");' % (a['name'], name))
        else:
            lines.append('        get => _tag == Tag.%s ? (%s)_state! : throw new System.InvalidOperationException($"Cannot access union member \\"%s\\" when %s stores {_tag}.");' % (a['name'], atype, a['name'], name))
        lines.append('        set')
        lines.append('        {')
        lines.append('            _tag = Tag.%s;' % a['name'])
        if payload['op'] == 'object' or payload['op'] == 'string':
            lines.append('            _state = value ?? throw new System.ArgumentNullException(nameof(value));')
        else:
            lines.append('            _state = value;')
        lines.append('        }')
        lines.append('    }')
    lines.append('')
    lines.append('    /// <summary>Writes the selected alternative to the wire.</summary>')
    lines.append('    public void Pack(global::Anki.Cozmo.Sdk.Clad.CladBinaryWriter cladWriter)')
    lines.append('    {')
    lines.append('        if (_state is null) throw new System.InvalidOperationException("Cannot pack an empty %s.");' % name)
    lines.append('        cladWriter.%s((%s)_tag);' % (tag_write, tag_type))
    lines.append('        switch (_tag)')
    lines.append('        {')
    for a in alts:
        lines.append(alt_pack_line(a))
    lines.append('            default: throw new System.InvalidOperationException("Cannot pack an empty %s.");' % name)
