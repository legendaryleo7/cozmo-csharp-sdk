def load_reference(sdk: Path):
    """Import ``cozmo.util`` from the reference SDK in an isolated package."""
    wheel = sdk / "cozmoclad" / "cozmoclad-3.6.6-py3-none-any.whl"
    util_py = sdk / "src" / "cozmo" / "util.py"
    if not util_py.is_file():
        raise SystemExit(f"missing reference file: {util_py}")
    if not wheel.is_file():
        raise SystemExit(f"missing bundled cozmoclad wheel: {wheel}")

    temp_dir = tempfile.TemporaryDirectory(prefix="cozmo-utilgen-")
    package = Path(temp_dir.name) / "cozmo"
    package.mkdir()
    (package / "__init__.py").write_text("", encoding="utf-8")
    shutil.copyfile(util_py, package / "util.py")
    (package / "_clad.py").write_text(
        "from cozmoclad.clad.externalInterface import messageGameToEngine\n"
        "_clad_to_engine_anki = messageGameToEngine.Anki\n",
        encoding="utf-8",
    )

    # The wheel is a zip, which Python can import from directly.
    sys.path.insert(0, str(wheel))
    sys.path.insert(0, temp_dir.name)
    import cozmo.util as util  # noqa: PLC0415 - deliberately late import

    return util, temp_dir


def double_literal(value) -> str:
    """Return a round-trippable C# double literal."""
    value = float(value)
    if math.isnan(value):
        return "double.NaN"
    if math.isinf(value):
        return "double.PositiveInfinity" if value > 0 else "double.NegativeInfinity"
    text = format(value, ".17g")
    return text + "d"


def int_literal(value) -> str:
    return str(int(value))


def uint_literal(value) -> str:
    return f"{int(value)}u"


def bool_literal(value) -> str:
    return "true" if value else "false"


def string_literal(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", "\\r")
        .replace("\n", "\\n")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def double_array(values) -> str:
    return "new double[] { " + ", ".join(double_literal(v) for v in values) + " }"


def tuple_row(items) -> str:
    return "(" + ", ".join(items) + ")"


class Output:
    def __init__(self) -> None:
        self._sections: list[str] = []

    def add(self, name: str, type_text: str, rows) -> None:
        lines = [f"    internal static readonly {type_text}[] {name} =", "    {"]
        for row in rows:
            lines.append(f"        {tuple_row(row)},")
        lines.extend(["    };", ""])
        self._sections.append("\n".join(lines))

    def build(self) -> str:
        parts = [
            LICENSE_HEADER,
            "// <auto-generated>",
            "// Generated by tools/utilgen/generate_util_goldens.py from the reference",
            "// Python implementation of cozmo/util.py. Do not edit by hand.",
            "// </auto-generated>",
            "",
            "namespace Cozmo.Tests;",
            "",
            "/// <summary>Golden values for utility conversions and arithmetic.</summary>",
            "internal static class UtilGoldenData",
            "{",
        ]
        parts.append("\n".join(self._sections).rstrip("\n"))
        parts.append("}")
        parts.append("")
        return "\n".join(parts)


